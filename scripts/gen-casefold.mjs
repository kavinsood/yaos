#!/usr/bin/env node
// Generates the frozen Unicode 15.1 tables used by src/core/paths (DESIGN §c.2):
//   src/core/paths/casefold15_1.ts  full case folding (CaseFolding.txt status C + F)
//   src/core/paths/assigned15_1.ts  assigned code point ranges (DerivedAge.txt, surrogates excluded)
//
// Usage:
//   node scripts/gen-casefold.mjs [--ucd DIR] [--check]
// Without --ucd the two UCD files are downloaded from unicode.org into a temp dir (never committed).
// --check regenerates in memory and fails if the committed files differ (reproducibility check).
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const UCD_BASE = "https://www.unicode.org/Public/15.1.0/ucd/";
const FILES = ["CaseFolding.txt", "DerivedAge.txt"];

const args = process.argv.slice(2);
const check = args.includes("--check");
const ucdIdx = args.indexOf("--ucd");
let ucdDir = ucdIdx >= 0 ? args[ucdIdx + 1] : null;

async function ensureUcd() {
	if (ucdDir) return ucdDir;
	ucdDir = mkdtempSync(join(tmpdir(), "ucd15.1-"));
	for (const name of FILES) {
		const res = await fetch(UCD_BASE + name);
		if (!res.ok) throw new Error(`download ${name}: HTTP ${res.status}`);
		writeFileSync(join(ucdDir, name), Buffer.from(await res.arrayBuffer()));
	}
	return ucdDir;
}

function sha256(text) {
	return createHash("sha256").update(text).digest("hex");
}

function hex(n) {
	return "0x" + n.toString(16).toUpperCase();
}

function wrap(items, perLine) {
	const lines = [];
	for (let i = 0; i < items.length; i += perLine) lines.push("\t" + items.slice(i, i + perLine).join(", ") + ",");
	return lines.join("\n");
}

function genCaseFold(text) {
	if (!text.startsWith("# CaseFolding-15.1.0.txt")) throw new Error("CaseFolding.txt is not version 15.1.0");
	const map = new Map();
	for (const raw of text.split("\n")) {
		const line = raw.split("#")[0].trim();
		if (!line) continue;
		const [code, status, mapping] = line.split(";").map((s) => s.trim());
		if (status !== "C" && status !== "F") continue;
		const cp = parseInt(code, 16);
		if (map.has(cp)) throw new Error(`duplicate C/F mapping for ${code}`);
		map.set(cp, mapping.split(/\s+/).map((h) => parseInt(h, 16)));
	}
	const keys = [...map.keys()].sort((a, b) => a - b);
	const flat = [];
	for (const k of keys) {
		const v = map.get(k);
		flat.push(hex(k), String(v.length), ...v.map(hex));
	}
	return {
		count: keys.length,
		body: wrap(flat, 12),
	};
}

function genAssigned(text) {
	if (!text.startsWith("# DerivedAge-15.1.0.txt")) throw new Error("DerivedAge.txt is not version 15.1.0");
	const ranges = [];
	for (const raw of text.split("\n")) {
		const line = raw.split("#")[0].trim();
		if (!line) continue;
		const [span] = line.split(";").map((s) => s.trim());
		const [a, b] = span.split("..");
		const lo = parseInt(a, 16);
		const hi = b === undefined ? lo : parseInt(b, 16);
		ranges.push([lo, hi]);
	}
	ranges.sort((x, y) => x[0] - y[0]);
	// Merge, then cut out the surrogates (never valid in a UTF-8 path) and the 66 noncharacters
	// (General_Category Cn: DerivedAge lists them as designated, but they are not assigned characters).
	const holes = [[0xd800, 0xdfff], [0xfdd0, 0xfdef]];
	for (let plane = 0; plane <= 0x10; plane++) holes.push([plane * 0x10000 + 0xfffe, plane * 0x10000 + 0xffff]);
	const merged = [];
	for (const [lo, hi] of ranges) {
		const last = merged[merged.length - 1];
		if (last && lo <= last[1] + 1) last[1] = Math.max(last[1], hi);
		else merged.push([lo, hi]);
	}
	let out = merged;
	for (const [hlo, hhi] of holes) {
		const next = [];
		for (const [lo, hi] of out) {
			if (hi < hlo || lo > hhi) { next.push([lo, hi]); continue; }
			if (lo < hlo) next.push([lo, hlo - 1]);
			if (hi > hhi) next.push([hhi + 1, hi]);
		}
		out = next;
	}
	const flat = out.flatMap(([lo, hi]) => [hex(lo), hex(hi)]);
	return { count: out.length, body: wrap(flat, 12) };
}

const dir = await ensureUcd();
const caseText = readFileSync(join(dir, "CaseFolding.txt"), "utf8");
const ageText = readFileSync(join(dir, "DerivedAge.txt"), "utf8");
const cf = genCaseFold(caseText);
const as = genAssigned(ageText);

const caseFile = `// GENERATED by scripts/gen-casefold.mjs from Unicode 15.1.0 CaseFolding.txt. Do not edit.
// FOLD rules version 1 (DESIGN §c.2, §c.10): changing this table requires a new fold rules version.
// Source sha256: ${sha256(caseText)}
// Entries: ${cf.count} (status C + F, full case folding).

/** Flattened [codePoint, n, folded_1 .. folded_n]*, ascending codePoint. */
export const CASE_FOLD_15_1: readonly number[] = [
${cf.body}
];
`;

const assignedFile = `// GENERATED by scripts/gen-casefold.mjs from Unicode 15.1.0 DerivedAge.txt. Do not edit.
// FOLD rules version 1 (DESIGN §c.2): code points assigned in Unicode 15.1 (surrogates and noncharacters excluded).
// Source sha256: ${sha256(ageText)}
// Ranges: ${as.count}.

/** Flattened inclusive [lo, hi]* ranges, ascending and disjoint. */
export const ASSIGNED_15_1: readonly number[] = [
${as.body}
];
`;

const targets = [
	[join(ROOT, "src/core/paths/casefold15_1.ts"), caseFile],
	[join(ROOT, "src/core/paths/assigned15_1.ts"), assignedFile],
];
if (check) {
	let ok = true;
	for (const [path, content] of targets) {
		const current = existsSync(path) ? readFileSync(path, "utf8") : null;
		if (current !== content) { console.error(`gen-casefold: ${path} differs from a fresh generation`); ok = false; }
	}
	if (!ok) process.exit(1);
	console.log("gen-casefold: committed tables match UCD 15.1.0");
} else {
	for (const [path, content] of targets) writeFileSync(path, content);
	console.log(`gen-casefold: ${cf.count} fold mappings, ${as.count} assigned ranges`);
}
